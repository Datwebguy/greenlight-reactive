/** Writes the contract interfaces the web app and agent use to web/src/lib/abi.ts. */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const names = ["GreenlightAccount", "GreenlightFactory", "GreenlightScorer", "GreenlightVenue"];
let out = "// Generated by scripts/export-abi.ts from the compiled contracts. Do not edit.\n";
for (const name of names) {
  const file = path.join(root, "artifacts/contracts", `${name}.sol`, `${name}.json`);
  const { abi } = JSON.parse(fs.readFileSync(file, "utf8"));
  out += `\nexport const ${name[0].toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
const token = JSON.parse(fs.readFileSync(path.join(root, "artifacts/contracts/GreenlightVenue.sol/VenueToken.json"), "utf8")).abi;
out += `\nexport const venueTokenAbi = ${JSON.stringify(token, null, 2)} as const;\n`;
fs.writeFileSync(path.join(root, "web/src/lib/abi.ts"), out);
console.log("wrote web/src/lib/abi.ts");
